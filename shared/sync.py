"""Copy the shared look into every tool of the suite.

    python shared/sync.py

Each tool must still build and run on its own, so instead of depending on this
folder it gets its own copy of:

  * the Qt theme (shared/qt/snake_theme.py) or the egui theme (shared/egui/snake_theme.rs),
  * its icon as icon.svg / icon.png / icon.ico (and a raw 64 px RGBA for egui and SDL),
  * for the Recompiler's SDL launcher, the palette as a C header.

Run it after changing anything under shared/. Tools whose folder is missing are skipped.
"""

from __future__ import annotations

import json
import re
import shutil
import subprocess
from pathlib import Path

SUITE = Path(__file__).resolve().parent.parent
SHARED = SUITE / "shared"
ICONS = SHARED / "icons"
QT_THEME = SHARED / "qt" / "snake_theme.py"
EGUI_THEME = SHARED / "egui" / "snake_theme.rs"


def rgba64(png: Path) -> bytes:
    """The icon as 64x64 straight RGBA bytes (what egui and SDL want)."""
    magick = shutil.which("magick") or shutil.which("convert")
    if not magick:
        raise SystemExit("ImageMagick is needed to make the 64 px icon (install it, or skip rgba64 tools).")
    out = subprocess.run([magick, str(png), "-resize", "64x64", "-depth", "8", "RGBA:-"],
                         check=True, capture_output=True).stdout
    assert len(out) == 64 * 64 * 4, len(out)
    return out


def palette_header() -> str:
    """The Qt theme's colour constants as a C header."""
    names = re.findall(r'^([A-Z_0-9]+) = "#([0-9a-fA-F]{6})"', QT_THEME.read_text(), re.M)
    lines = ["/* Snake's Suite palette (Snake Dark). Generated by Snake's Suite/shared/sync.py; do not edit. */",
             "#ifndef SNAKE_PALETTE_H", "#define SNAKE_PALETTE_H", ""]
    for name, hexa in names:
        r, g, b = (int(hexa[i:i + 2], 16) for i in (0, 2, 4))
        lines.append(f"#define SNAKE_{name} {r}, {g}, {b}")
    return "\n".join(lines + ["", "#endif", ""])


def icon_header(data: bytes) -> str:
    body = ",".join(str(b) for b in data)
    return ("/* Snake's Suite icon, 64x64 RGBA. Generated by Snake's Suite/shared/sync.py; do not edit. */\n"
            "static const unsigned char snake_icon_rgba[64 * 64 * 4] = {" + body + "};\n")


def write(path: Path, data: str | bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    old = path.read_bytes() if path.exists() else None
    new = data.encode() if isinstance(data, str) else data
    if old != new:
        path.write_bytes(new)
        print("  updated", path)


def sync_tool(tool: dict, root: Path) -> None:
    icon = tool.get("icon", tool["id"])
    assets = tool.get("assets", {})
    if "qt_theme" in tool:
        write(root / tool["qt_theme"], QT_THEME.read_text())
    if "egui_theme" in tool:
        write(root / tool["egui_theme"], EGUI_THEME.read_text())
    if "c_palette" in tool:
        write(root / tool["c_palette"], palette_header())
    if "dir" in assets:
        adir = root / assets["dir"]
        names = [p.stem for p in ICONS.glob("*.svg")] if assets.get("all_icons") else [icon]
        for name in names:
            target = "icon" if name == icon else name
            for ext in ("svg", "png", "ico"):
                src = ICONS / f"{name}.{ext}"
                if src.exists():
                    write(adir / f"{target}.{ext}", src.read_bytes())
        if assets.get("rgba64"):
            write(adir / "icon64.rgba", rgba64(ICONS / f"{icon}.png"))
    if tool.get("id") == "suite":
        # The one-file app carries the catalogue, so it knows every tool without the kit.
        write(root / "snakes_suite" / "catalogue.json", (SUITE / "suite.json").read_bytes())
    if "c_icon" in assets:
        write(root / assets["c_icon"], icon_header(rgba64(ICONS / f"{icon}.png")))


def main() -> None:
    catalogue = json.loads((SUITE / "suite.json").read_text())
    for tool in catalogue["tools"] + [catalogue["hub"]]:
        root = (SUITE / tool["folder"]).resolve()
        print(f"{tool['name']}: {root}")
        if not root.is_dir():
            print("  (not found, skipped)")
            continue
        sync_tool(tool, root)


if __name__ == "__main__":
    main()
